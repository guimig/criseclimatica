'use strict';
const assert=require('node:assert/strict');
const {HOUR,identity,scale,resolution,aggregateRain,simplify,segments,ticks,readingAt,observationGaps,nearestIndex}=require('../web/chart-utils.js');
const start=Date.parse('2026-11-26T09:00:00Z');
const rows=Array.from({length:24},(_,i)=>({time:new Date(start+(i+1)*HOUR).toISOString(),value:i===5?0:1}));
const original=JSON.stringify(rows);
const groups=aggregateRain(rows,start,24,3);
assert.equal(groups.length,8);assert.equal(groups[1].value,2);
assert.equal(groups.reduce((n,p)=>n+p.value,0),23);
assert.equal(groups[0].start_at,new Date(start).toISOString());assert.equal(groups[0].time,new Date(start+3*HOUR).toISOString());
assert.equal(JSON.stringify(rows),original);
const missing=aggregateRain(rows.filter((_,i)=>i!==1),start,24,3)[0];
assert.equal(missing.value,null);assert.equal(missing.partialValue,2);assert.equal(missing.validHours,2);assert.equal(missing.status,'partial');
assert.equal(aggregateRain([],start,24,6)[0].status,'missing');
assert.equal(aggregateRain([{...rows[0],value:0}],start,1,1)[0].value,0);
assert.equal(aggregateRain([...rows,rows[0]],start,24,3)[0].value,3);
assert.equal(aggregateRain([...rows,{...rows[0],value:7},rows[0]],start,24,3)[0].value,null,'conflicting duplicates cannot recover silently');
assert.equal(aggregateRain([{...rows[0],value:-1}],start,1,1)[0].value,null);
assert.equal(aggregateRain([{time:new Date(start+HOUR+1).toISOString(),value:99}],start,1,1)[0].value,null,'off-grid timestamps cannot fill an expected hour');
assert.equal(aggregateRain(rows,start,5,3)[1].expectedHours,2);
assert.equal(resolution(24,300),1);assert.equal(resolution(72,300),3);assert.equal(resolution(240,300),6);
assert.ok(resolution(72,200,3)>=6,'narrow multi-model plots need wider slots');
assert.equal(new Set(['best_match','ecmwf_ifs025','ncep_gfs_global'].map(key=>identity(key,'gust_kmh').dash)).size,3);
assert.equal(new Set(['best_match','ecmwf_ifs025','ncep_gfs_global'].map(key=>identity(key,'temperature_c').shape)).size,3);
const station=identity('cemaden-rain:A','wind_kmh');
assert.equal(station.color,identity('cemaden-rain:A','gust_kmh').color);
assert.notEqual(station.dash,identity('cemaden-rain:A','gust_kmh').dash);
assert.deepEqual(identity('cemaden-rain:A','wind_kmh'),station);
assert.notEqual(identity('cemaden-rain:A','wind_kmh',true).color,station.color);
const dense=Array.from({length:6000},(_,i)=>({time:new Date(start+i*1000).toISOString(),value:i===1999?900:i===3001?-50:i%11}));
const reduced=simplify(dense,start,start+6000000,100);
assert.ok(reduced.length<=402);assert.ok(reduced.some(p=>p.value===900));assert.ok(reduced.some(p=>p.value===-50));
assert.equal(reduced[0],dense[0]);assert.equal(reduced.at(-1),dense.at(-1));
assert.equal(segments([rows[0],{...rows[1],value:null},rows[2]],HOUR).length,2);
assert.equal(segments([rows[0],rows[3]],HOUR).length,2);
assert.equal(segments([rows[0],rows[1]],HOUR).length,1);
assert.equal(scale([0,5]).low,0);assert.ok(scale([-5,-2],true).low<=-6);assert.ok(scale([]).high>0);
assert.equal(nearestIndex([],2),-1);assert.equal(nearestIndex([1,3,6],-5),0);assert.equal(nearestIndex([1,3,6],9),2);assert.equal(nearestIndex([1,3,6],2),0);assert.equal(nearestIndex([1,3,6],2.5),1);
const sample={...rows[0],start_at:new Date(start-23*HOUR).toISOString()};
assert.equal(readingAt({points:[sample],gapMs:HOUR},start-12*HOUR),null,'a rolling total is not a value at every instant inside its window');
assert.equal(readingAt({points:[sample],gapMs:HOUR},start+HOUR),sample);
assert.equal(readingAt({points:[sample],gapMs:HOUR},start+2*HOUR),null);
assert.equal(readingAt({points:[sample]},start-12*HOUR,true),sample,'interval lookup is explicit and reserved for non-overlapping forecasts');
assert.ok(observationGaps([{points:[sample],gapMs:HOUR}],start-24*HOUR,start+HOUR).length);
const marks=ticks(start,start+168*HOUR,300);assert.equal(marks[0],start);assert.equal(marks.at(-1),start+168*HOUR);
assert.ok(marks.length<=6);
console.log('Chart data checks passed: exact intervals, zero, partial/missing hours, conflicts, stable identity, responsive resolution, extrema, gaps and unchanged raw values.');
